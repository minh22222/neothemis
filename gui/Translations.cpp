QString translated_text(const char* key, bool vietnamese) {
    for (const auto& entry : kUiText) {
        if (std::strcmp(entry.key, key) == 0) {
            return QString::fromUtf8(vietnamese ? entry.vi : entry.en);
        }
    }
    return QString::fromUtf8(key);
}

